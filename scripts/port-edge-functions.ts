// Generates src/lib/edge-fns/*.server.ts from supabase/functions/* so the site's own
// server (teachermate.org.cn) runs the background services itself.
// supabase/functions stays the single source of truth: edit there, then run
//   bun scripts/port-edge-functions.ts
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import { join } from "node:path";

const SRC = "supabase/functions";
const OUT = "src/lib/edge-fns";
const HEADER = "// @ts-nocheck\n// GENERATED by scripts/port-edge-functions.ts from supabase/functions — do not edit.\n";

function outName(dir: string, file: string): string {
  if (dir === "_shared") return `_shared-${file.replace(/\.ts$/, "")}`;
  if (file === "index.ts") return dir;
  return `${dir}-${file.replace(/\.ts$/, "")}`;
}

function rewriteImports(code: string, dir: string): string {
  return code
    .replace(/^import\s*\{\s*serve\s*\}\s*from\s*["']https:\/\/deno\.land\/[^"']+["'];?\s*$/gm, "")
    .replace(/["'](?:https:\/\/esm\.sh\/|npm:)@supabase\/supabase-js@[\d.]+\/cors["']/g, '"@supabase/supabase-js/cors"')
    .replace(/["'](?:https:\/\/esm\.sh\/|npm:)@supabase\/supabase-js(?:@[\d.]+)?["']/g, '"./_supabase.server"')
    .replace(/["']\.\.\/_shared\/([\w-]+)\.ts["']/g, (_m, f) => `"./_shared-${f}.server"`)
    .replace(/["']\.\/([\w-]+)\.ts["']/g, (_m, f) => `"./${outName(dir, `${f}.ts`)}.server"`);
}

function port(dir: string, file: string): string {
  const raw = readFileSync(join(SRC, dir, file), "utf8");
  let code = rewriteImports(raw, dir);
  const unsupported = code.match(/^import[^\n]*from\s*["'](https?:|npm:|jsr:)[^"']+["']/m);
  if (unsupported) throw new Error(`${dir}/${file}: unsupported import ${unsupported[0]}`);
  const isEntry = file === "index.ts";
  const usesDeno = /\bDeno\./.test(code);
  code = code.replace(/\bDeno\.serve\(/g, "serve(");
  let prelude = "";
  if (isEntry) {
    prelude = 'import { Deno, createServe } from "./_deno-shim.server";\nconst { serve, handler } = createServe();\nexport default handler;\n';
  } else if (usesDeno) {
    prelude = 'import { Deno } from "./_deno-shim.server";\n';
  }
  return HEADER + prelude + code;
}

const names: string[] = [];
for (const dir of readdirSync(SRC).sort()) {
  const full = join(SRC, dir);
  if (!statSync(full).isDirectory()) continue;
  for (const file of readdirSync(full)) {
    if (!file.endsWith(".ts") || /(_test|\.test)\.ts$/.test(file)) continue;
    writeFileSync(join(OUT, `${outName(dir, file)}.server.ts`), port(dir, file));
  }
  if (dir !== "_shared" && existsSync(join(full, "index.ts"))) names.push(dir);
}

const registry =
  HEADER.replace("// @ts-nocheck\n", "") +
  "type EdgeModule = { default: (req: Request) => Promise<Response> };\n\n" +
  "/** Background services the site's own server runs instead of the overseas edge runtime. */\n" +
  "export const LOCAL_EDGE_FUNCTIONS: Record<string, () => Promise<EdgeModule>> = {\n" +
  names.map((n) => `  "${n}": () => import("./${n}.server"),`).join("\n") +
  "\n};\n";
writeFileSync(join(OUT, "registry.server.ts"), registry);
console.log(`ported ${names.length} functions:`, names.join(", "));
